"""HTTP API for local audio generation.

Endpoint map:
  GET    /health                  liveness + device + provider readiness
  GET    /v1/models               what can generate what, with licences and params
  POST   /v1/audio/speech         TTS; waits inline (seconds) then returns audio_url
  POST   /v1/audio/music          enqueues; returns a job to poll (minutes)
  POST   /v1/audio/sfx            enqueues; returns a job to poll
  GET    /v1/jobs, /v1/jobs/{id}  job status; DELETE cancels a queued job
  GET    /v1/audio/{id}           the generated bytes; DELETE removes them
  GET/POST/DELETE /v1/voices      voice-clone reference samples
  GET    /v1/storage              disk usage
"""
from __future__ import annotations

import asyncio
import contextlib
import logging
import math

from fastapi import FastAPI, File, Form, HTTPException, Query, UploadFile
from fastapi.middleware.cors import CORSMiddleware
from fastapi.responses import FileResponse, JSONResponse

from . import storage
from .auth import api_key_middleware
from .config import get_settings
from .jobs import Job, JobQueue, JobStatus
from .providers.base import Capability, GenerateRequest, check_audio_sane
from .registry import get_registry
from .schemas import GenerateBody, SpeechBody

settings = get_settings()
logging.basicConfig(
    level=settings.log_level,
    format="%(asctime)s %(levelname)-7s %(name)s: %(message)s",
)
log = logging.getLogger("audiogen")

queue = JobQueue(max_concurrent=settings.max_concurrent_jobs)

# TTS is quick, so the client waits inline rather than polling. Past this the
# request returns a job id instead of blocking a proxy connection forever.
SPEECH_INLINE_WAIT = 180.0


@contextlib.asynccontextmanager
async def lifespan(app: FastAPI):
    reg = get_registry()
    log.info("device=%s providers=%d available=%d",
             settings.device, len(reg.all()), sum(p.available() for p in reg.all()))
    sweeper = asyncio.create_task(_sweep_idle_models())
    try:
        yield
    finally:
        sweeper.cancel()
        with contextlib.suppress(asyncio.CancelledError):
            await sweeper


async def _sweep_idle_models() -> None:
    """Return VRAM when a model has gone unused. Matters on a shared GPU."""
    timeout = settings.model_idle_timeout
    if timeout <= 0:
        return
    while True:
        await asyncio.sleep(max(30, timeout // 4))
        try:
            get_registry().sweep_idle(timeout)
        except Exception:                              # noqa: BLE001
            log.exception("idle sweep failed")


app = FastAPI(
    title="Audio Performance Generator API",
    version="0.1.0",
    lifespan=lifespan,
)
app.middleware("http")(api_key_middleware)
app.add_middleware(
    CORSMiddleware,
    allow_origins=settings.cors_origins,
    allow_credentials=False,
    allow_methods=["*"],
    allow_headers=["*"],
)


def _gpu_info() -> dict | None:
    try:
        import torch
        if not torch.cuda.is_available():
            return None
        free, total = torch.cuda.mem_get_info()
        return {
            "name": torch.cuda.get_device_name(0),
            "vram_total_gb": round(total / 1024**3, 2),
            "vram_free_gb": round(free / 1024**3, 2),
        }
    except Exception:                                  # noqa: BLE001
        return None


@app.get("/health")
def health():
    reg = get_registry()
    providers = reg.all()
    available = sum(p.available() for p in providers)
    return {
        "status": "ok" if available else "degraded",
        "device": settings.device,
        "providers_available": available,
        "providers_total": len(providers),
        "gpu": _gpu_info(),
        "jobs": queue.stats(),
    }


