def _run_generation(provider, req: GenerateRequest, kind: str):
    """Build the thread-side callable the job queue will execute."""
    def _work(job: Job) -> dict:
        job.message = f"generating with {provider.id}"
        # Held for the whole generation so the idle sweeper cannot unload the
        # model while this job is still running on it.
        with provider.in_use():
            result = provider.generate(req)

        # Fail loudly on silent/degenerate output rather than storing a clip of
        # nothing and reporting success. Only meaningful for WAV; the cloud
        # providers return mp3 and are skipped.
        if result.mime == "audio/wav":
            check_audio_sane(result.audio)

        audio_id = storage.save_audio(
            result.audio,
            suffix=".mp3" if result.mime == "audio/mpeg" else ".wav",
            meta={
                "kind": kind,
                "provider": result.provider_id,
                "prompt": req.prompt[:500],
                "sample_rate": result.sample_rate,
                "duration": result.duration,
                "mime": result.mime,
            },
        )
        return {
            "audio_id": audio_id,
            "meta": {
                "duration": result.duration,
                "sample_rate": result.sample_rate,
                "mime": result.mime,
                "provider": result.provider_id,
            },
        }
    return _work


def _resolve(capability: Capability, provider_id: str | None):
    reg = get_registry()
    try:
        return reg.resolve(capability, provider_id)
    except KeyError as exc:
        raise HTTPException(404, str(exc)) from exc
    except ValueError as exc:
        raise HTTPException(400, str(exc)) from exc
    except RuntimeError as exc:
        raise HTTPException(503, str(exc)) from exc


def _validated_seconds(provider, seconds: float | None, params: dict) -> float | None:
    """Check a requested duration against the resolved provider's own bounds.

    Providers advertise a `seconds` param with a range. When one does, the
    request must fall inside it -- a clearer failure than a job that dies later
    inside the model or the cloud API. When a provider advertises no duration
    at all (TTS length follows the text), the value is dropped rather than
    passed on: code that never declared a bound must not receive an unbounded
    number. Both the top-level field and params["seconds"] are covered, since
    providers read either.
    """
    raw = seconds if seconds is not None else params.get("seconds")
    spec = next((p for p in provider.params() if p.name == "seconds"), None)
    if spec is None:
        params.pop("seconds", None)
        return None
    if raw is None:
        return None
    try:
        value = float(raw)
    except (TypeError, ValueError):
        raise HTTPException(422, f"seconds must be a number, got {raw!r}") from None
    lo, hi = spec.minimum, spec.maximum
    if not math.isfinite(value) or (lo is not None and value < lo) or (hi is not None and value > hi):
        span = f"{lo:g}-{hi:g}" if lo is not None and hi is not None else (
            f">= {lo:g}" if lo is not None else f"<= {hi:g}")
        raise HTTPException(422, f"seconds must be {span} for {provider.id} (got {raw})")
    params["seconds"] = value
    return value


def _job_payload(job: Job) -> dict:
    payload = job.public()
    payload["audio_url"] = f"/v1/audio/{job.audio_id}" if job.audio_id else None
    return payload


@app.post("/v1/audio/speech")
async def generate_speech(body: SpeechBody, wait: bool = Query(True)):
    prompt = body.resolved_prompt()
    if not prompt or not prompt.strip():
        raise HTTPException(422, "prompt/input is empty")

    provider = _resolve(Capability.VOICE, body.provider)
    params = dict(body.params)
    seconds = _validated_seconds(provider, body.seconds, params)
    req = GenerateRequest(
        prompt=prompt,
        capability=Capability.VOICE,
        voice_id=body.resolved_voice(),
        seconds=seconds,
        seed=body.seed,
        params=params,
    )
    job = queue.submit("speech", _run_generation(provider, req, "voice"),
                       meta={"provider": provider.id})
    if wait:
        await queue.wait_for(job, timeout=SPEECH_INLINE_WAIT)
        if job.status is JobStatus.ERROR:
            raise HTTPException(500, job.error or "generation failed")
    return JSONResponse(_job_payload(job), status_code=200 if job.audio_id else 202)


async def _enqueue(capability: Capability, body: GenerateBody, kind: str):
    provider = _resolve(capability, body.provider)
    params = dict(body.params)
    seconds = _validated_seconds(provider, body.seconds, params)
    req = GenerateRequest(
        prompt=body.prompt,
        capability=capability,
        voice_id=body.voice_id,
        seconds=seconds,
        seed=body.seed,
        params=params,
    )
    job = queue.submit(kind, _run_generation(provider, req, kind), meta={"provider": provider.id})
    return JSONResponse(_job_payload(job), status_code=202)


@app.post("/v1/audio/music")
async def generate_music(body: GenerateBody):
    return await _enqueue(Capability.MUSIC, body, "music")


@app.post("/v1/audio/sfx")
async def generate_sfx(body: GenerateBody):
    return await _enqueue(Capability.SFX, body, "sfx")


@app.get("/v1/jobs")
def list_jobs(limit: int = Query(50, ge=1, le=200)):
    # Same shape as GET /v1/jobs/{id}, including audio_url, so a listed job
    # can be recovered without a second request.
    return {"jobs": [
        {**j, "audio_url": f"/v1/audio/{j['audio_id']}" if j.get("audio_id") else None}
        for j in queue.list(limit)
    ]}


@app.get("/v1/jobs/{job_id}")
def get_job(job_id: str):
    job = queue.get(job_id)
    if job is None:
        raise HTTPException(404, "unknown job")
    return _job_payload(job)


@app.delete("/v1/jobs/{job_id}")
def cancel_job(job_id: str):
    job = queue.get(job_id)
    if job is None:
        raise HTTPException(404, "unknown job")
    cancelled = queue.cancel(job_id)
    if not cancelled:
        # Be honest: work already inside torch cannot be interrupted.
        raise HTTPException(409, f"job is {job.status.value} and can no longer be cancelled")
    return _job_payload(job)


@app.get("/v1/audio/{audio_id}")
def get_audio(audio_id: str):
    try:
        path = storage.audio_path(audio_id)
    except ValueError as exc:
        raise HTTPException(400, str(exc)) from exc
    if path is None:
        raise HTTPException(404, "unknown audio id")
    meta = storage.audio_meta(audio_id) or {}
    return FileResponse(
        path,
        media_type=meta.get("mime", "audio/wav"),
        headers={"Cache-Control": "public, max-age=31536000, immutable"},
    )


@app.delete("/v1/audio/{audio_id}")
def remove_audio(audio_id: str):
    try:
        ok = storage.delete_audio(audio_id)
    except ValueError as exc:
        raise HTTPException(400, str(exc)) from exc
    if not ok:
        raise HTTPException(404, "unknown audio id")
    return {"deleted": audio_id}


